"""Add read-only launcher enumeration and a user-initiated open bridge.
Runs after setup-native.sh and install-life-native.py, before Capacitor sync.
Do not add QUERY_ALL_PACKAGES or alter existing Maya native commands.
"""
from pathlib import Path
import shutil

base = Path("android/app/src/main")
java = base / "java/com/tanim/maya"
bridge = java / "MayaBridge.java"
catalog = java / "MayaAppCatalog.java"
manifest = base / "AndroidManifest.xml"
if not bridge.is_file() or not manifest.is_file():
    raise SystemExit("Maya native bridge/manifest missing; abort")

s = bridge.read_text(encoding="utf-8")
anchor = "    @JavascriptInterface\n    public void requestSms() {"
# Each bridge method is added independently so upgrading a tree generated by an
# older installer (which already has some of the methods) adds only the missing ones.
methods = {
    "public String listLaunchableApps()": """    /** Only launchable apps visible to Maya on Android. */
    @JavascriptInterface
    public String listLaunchableApps() {
        return MayaAppCatalog.list(ctx);
    }

""",
    "public String launchListedApp(String": """    /** User-selected pair is revalidated by native Android before launching. */
    @JavascriptInterface
    public String launchListedApp(String packageName, String activityName) {
        return MayaAppCatalog.launch(ctx, packageName, activityName);
    }

""",
    "public String requestLaunchNotifications()": """    /** Settings control: request notification permission while Maya is visible. */
    @JavascriptInterface
    public String requestLaunchNotifications() {
        return MayaBackgroundLaunch.requestPermission();
    }

""",
}
if s.count(anchor) != 1:
    raise SystemExit("MayaBridge bridge method anchor changed; patch cancelled")
changed = False
for signature, snippet in methods.items():
    if signature not in s:
        s = s.replace(anchor, snippet + anchor, 1)
        changed = True
if changed:
    bridge.write_text(s, encoding="utf-8")

shutil.copyfile("native-app-launcher/MayaAppCatalog.java", catalog)
shutil.copyfile("native-app-launcher/MayaBackgroundLaunch.java", java / "MayaBackgroundLaunch.java")

# Register the foreground watcher from MainActivity.onCreate, before onStart/
# onResume can run, so a late registration never misreads the foreground state.
main_activity = java / "MainActivity.java"
watch_line = "MayaBackgroundLaunch.watch(this);"
if main_activity.is_file() and watch_line not in main_activity.read_text(encoding="utf-8"):
    attach_anchor = "MayaBridge.attach(this, getBridge().getWebView());"
    source = main_activity.read_text(encoding="utf-8")
    if source.count(attach_anchor) != 1:
        raise SystemExit("MainActivity attach anchor changed; patch cancelled")
    main_activity.write_text(
        source.replace(attach_anchor, watch_line + "\n        " + attach_anchor, 1),
        encoding="utf-8",
    )

# The deferred background launch needs POST_NOTIFICATIONS on Android 13+.
# Permission is requested only from the Maya Settings control, never at startup.
from xml.dom import minidom
doc = minidom.parse(str(manifest))
root = doc.documentElement
ns = "http://schemas.android.com/apk/res/android"
permission = "android.permission.POST_NOTIFICATIONS"
if not any(n.getAttributeNS(ns, "name") == permission for n in root.getElementsByTagName("uses-permission")):
    node = doc.createElement("uses-permission")
    node.setAttributeNS(ns, "android:name", permission)
    root.appendChild(node)
    manifest.write_bytes(doc.toxml(encoding="utf-8"))

# Monochrome notification icon (alpha-masked by the system; not the adaptive launcher icon).
drawable_dir = base / "res" / "drawable"
drawable_dir.mkdir(parents=True, exist_ok=True)
shutil.copyfile("native-app-launcher/maya_launch_notify.xml", drawable_dir / "maya_launch_notify.xml")

# The existing scripts/ensure-launcher-query.py adds the minimal MAIN/LAUNCHER
# package visibility declaration. Refuse to build an unqueryable launcher.
doc = minidom.parse(str(manifest))
root = doc.documentElement
queries = root.getElementsByTagName("queries")
if not queries:
    raise SystemExit("Expected <queries> MAIN/LAUNCHER was not installed")
ns = "http://schemas.android.com/apk/res/android"
intents = queries[0].getElementsByTagName("intent")
if not any(
    any(a.getAttributeNS(ns, "name") == "android.intent.action.MAIN"
        for a in node.getElementsByTagName("action"))
    and any(c.getAttributeNS(ns, "name") == "android.intent.category.LAUNCHER"
        for c in node.getElementsByTagName("category"))
    for node in intents
):
    raise SystemExit("Android MAIN/LAUNCHER package visibility query missing")
if "QUERY_ALL_PACKAGES" in manifest.read_text(encoding="utf-8"):
    raise SystemExit("Reject broad package visibility permission")

print("Maya named-app launcher installed: visible launcher activities only; no broad app permission. Background launches defer to a tap-to-open notification.")
